import dotenv from 'dotenv';
dotenv.config();
import app from './app';
import { connectPostgres, initializePostgres } from './config/db';
import { connectMongo } from './config/mongo';
import { connectRedis } from './config/redis';
import { seedStations } from './models/stationModel';
import { ensureDefaultAdmin } from './models/userModel';
import { syncLiveReadings } from './services/liveAirQuality';
const PORT = Number(process.env.PORT || 5000);
const start = async () => {
  await connectPostgres();
  await initializePostgres();
  await connectMongo();
  connectRedis();
  await ensureDefaultAdmin();
  await seedStations();
  app.listen(PORT, () => console.log(`Server running on http://localhost:${PORT}`));
  void syncLiveReadings().catch((error) => console.warn('Initial air-quality refresh failed; saved readings remain available:', error));
  setInterval(() => { void syncLiveReadings().catch((error) => console.warn('Air-quality refresh failed:', error)); }, 15 * 60 * 1000);
};
start().catch((error) => { console.error('Unable to start AirWatch:', error); process.exit(1); });
